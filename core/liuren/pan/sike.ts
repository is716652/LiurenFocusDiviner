class LrSike {
  /* 四课：干→干阴→支→支阴（规范《四课排法》）
     原 buildChart / buildChartAncient 各自内联的四行，抽为唯一实现（等价抽取，判定不变） */
  static sikeOf(tp: Record<string, string>, dg: string, dz: string): Keg[] {
    const g1 = tp[LrBase.JI_GONG[dg]];
    const g2 = tp[g1];
    const g3 = tp[dz];
    const g4 = tp[g3];
    return [
      { x: g1, s: dg },
      { x: g2, s: g1 },
      { x: g3, s: dz },
      { x: g4, s: g3 }
    ];
  }
}
